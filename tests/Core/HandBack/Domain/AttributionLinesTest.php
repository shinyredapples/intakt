<?php

declare(strict_types=1);

namespace Intakt\Tests\Core\HandBack\Domain;

use Intakt\Core\HandBack\Domain\AttributionLines;
use PHPUnit\Framework\Attributes\CoversClass;
use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\TestCase;

#[CoversClass(AttributionLines::class)]
final class AttributionLinesTest extends TestCase
{
    public function testACoAuthorTrailerIsStrippedInAnyCase(): void
    {
        $message = "Add the check\n\nBody text.\n\nSigned-off-by: Dev <dev@example.invalid>\nco-AUTHORED-by: Bot <bot@example.invalid>\n";

        self::assertSame("Add the check\n\nBody text.\n\nSigned-off-by: Dev <dev@example.invalid>\n", AttributionLines::strippedFrom($message));
    }

    /**
     * @return iterable<string, array{string}>
     */
    public static function generatedLines(): iterable
    {
        yield 'with a mark in front' => ["\u{1F916} Generated with [a tool](https://example.invalid)"];
        yield 'by' => ['Generated by a tool'];
        yield 'as a trailer' => ['Generated-by: a tool'];
        yield 'indented' => ['   generated WITH a tool'];
    }

    #[DataProvider('generatedLines')]
    public function testAGeneratedLineIsStripped(string $line): void
    {
        self::assertSame("Add the check\n", AttributionLines::strippedFrom("Add the check\n\n".$line."\n"));
    }

    public function testTheBlankLinesAStrippedParagraphLeavesCollapseIntoOne(): void
    {
        $message = "Add the check\n\nGenerated with a tool\n\nCo-Authored-By: Bot <bot@example.invalid>\n\nMore text.\n";

        self::assertSame("Add the check\n\nMore text.\n", AttributionLines::strippedFrom($message));
    }

    public function testAMessageWithoutAttributionIsKeptByteForByte(): void
    {
        $message = "Add the check\n\n\n\nA line that mentions co-authored-by: in passing.\nThe code was generated  by hand, and regenerated with care.  \n\n";

        self::assertSame($message, AttributionLines::strippedFrom($message));
    }

    public function testAMessageWithWindowsLineEndingsKeepsThemWhenATrailerIsStripped(): void
    {
        self::assertSame("Subject\r\n\r\nBody\r\n", AttributionLines::strippedFrom("Subject\r\n\r\nBody\r\nCo-authored-by: x\r\n"));
    }

    public function testAParagraphStrippedBetweenWindowsParagraphsLeavesOneWindowsBlankLine(): void
    {
        $message = "Subject\r\n\r\nGenerated with a tool\r\n\r\nMore text.\r\n";

        self::assertSame("Subject\r\n\r\nMore text.\r\n", AttributionLines::strippedFrom($message));
    }

    public function testATrailerWithAWindowsEndingDoesNotMakeAUnixMessageMixed(): void
    {
        self::assertSame("Subject\n\nBody\n", AttributionLines::strippedFrom("Subject\n\nBody\nCo-authored-by: x\r\n"));
    }

    public function testASingleKeptLineWithoutAnEndingTakesTheWindowsEndingOfTheMessage(): void
    {
        self::assertSame("Subject\r\n", AttributionLines::strippedFrom("Generated by a tool\r\nSubject"));
    }

    public function testASingleKeptLineKeepsItsWindowsEndingWhenTheStrippedLastLineHasNone(): void
    {
        self::assertSame("Subject\r\n", AttributionLines::strippedFrom("Subject\r\nCo-authored-by: x"));
    }

    public function testASingleKeptLineKeepsItsWindowsEndingWhenTheStrippedLastLineHasOne(): void
    {
        self::assertSame("Subject\r\n", AttributionLines::strippedFrom("Subject\r\nCo-authored-by: x\r\n"));
    }

    public function testASingleKeptLineKeepsItsUnixEndingWhenOnlyTheStrippedTrailerHasAWindowsOne(): void
    {
        self::assertSame("Subject\n", AttributionLines::strippedFrom("Subject\nCo-authored-by: x\r\n"));
    }

    public function testASingleKeptLineWithoutAnEndingInAUnixMessageGetsAUnixEnding(): void
    {
        self::assertSame("Subject\n", AttributionLines::strippedFrom("Generated by a tool\nSubject"));
    }

    public function testKeptLinesAfterAStrippedFirstLineKeepTheirWindowsEndings(): void
    {
        self::assertSame("Subject\r\nBody\r\n", AttributionLines::strippedFrom("Generated by a tool\r\nSubject\r\nBody"));
    }

    public function testTrailingWhiteSpaceBeforeAWindowsEndingIsDropped(): void
    {
        self::assertSame("Body\r\n", AttributionLines::strippedFrom("Body  \r\nCo-authored-by: x\r\n\r\n\r\n"));
    }

    public function testAMessageOfOnlyAttributionBecomesEmpty(): void
    {
        self::assertSame('', AttributionLines::strippedFrom("Co-authored-by: Bot <bot@example.invalid>\n"));
    }

    public function testAMessageThatIsNoUtf8IsStillStripped(): void
    {
        self::assertSame("Caf\xE9\n", AttributionLines::strippedFrom("Caf\xE9\n\nCo-authored-by: Bot <bot@example.invalid>\n"));
    }
}
